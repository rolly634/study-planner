// ── 項目一覧 ─────────────────────────
export const ITEMS = {};
export const CHAPTERS = CH.map((ch, ci) => {
  const book = BOOKS[ch.book];
  const ids = ch.items.map((it) => {
    const id = `${ch.book}-${it.no}`;
    const label = book.showNo
      ? `${book.short} ${it.no}${it.title ? ' ' + it.title : ''}`
      : `${book.subject === 'physics' && ch.book !== 'RYO' ? book.short + ' ' : ch.book === 'RYO' ? '良問 ' : ''}${it.title}`;
    ITEMS[id] = { id, book: ch.book, no: it.no, title: it.title, chapter: ch.name, chapterIndex: ci, subject: book.subject, label };
    return id;
  });
  return { ...ch, index: ci, subject: book.subject, stream: book.stream, ids };
});

// 期間キーと周回から、その期間に割り当てられた項目を返す
export function itemsForPeriod(periodKey) {
  const out = [];
  for (const ch of CHAPTERS) {
    ch.weeks.forEach((w, roundIdx) => {
      if (w === periodKey) {
        for (const id of ch.ids) out.push({ id, round: roundIdx + 1, stream: ch.stream, subject: ch.subject, chapter: ch.name });
      }
    });
  }
  return out;
}
