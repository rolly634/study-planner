// c(本, 章名, 週, 範囲[, 開始番号])  範囲: [from, to] か 項目名の配列（通し番号を自動で振る。開始番号を指定できる）
const CH = [];
const counters = {};
function c(book, name, weeks, spec, start) {
  const ws = Array.isArray(weeks) ? weeks : [weeks];
  if (start) counters[book] = start - 1;
  let items;
  if (Array.isArray(spec) && typeof spec[0] === 'number') {
    items = [];
    for (let n = spec[0]; n <= spec[1]; n++) items.push({ no: n, title: '' });
    counters[book] = spec[1];
  } else {
    items = spec.map((t) => {
      counters[book] = (counters[book] || 0) + 1;
      return { no: counters[book], title: t };
    });
  }
  CH.push({ book, name, weeks: ws, items });
}

