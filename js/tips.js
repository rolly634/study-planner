// subject と章名の配列から、日付で回しながら TIPS を1つ選ぶ
export function pickTip(subject, chapterNames, seed) {
  const bank = TIPS[subject] || {};
  const pool = [];
  for (const name of chapterNames) {
    for (const [kw, list] of Object.entries(bank)) {
      if (kw === '' || name.includes(kw)) for (const t of list) if (!pool.includes(t)) pool.push(t);
    }
  }
  const list = pool.length ? pool : GENERAL[subject] || [];
  if (!list.length) return null;
  return list[seed % list.length];
}
